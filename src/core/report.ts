import { AgentInfo } from './agents';
import { Insight } from './health';
import { totalTokens } from './pricing';
import { SessionIndex, SessionInfo } from './sessions';
import { fmtTokens, fmtUSD } from './util';

function pct(n: number): string {
    return (100 * n).toFixed(0) + '%';
}

function inRange(s: SessionInfo, cutoff: number): boolean {
    return s.lastTs >= cutoff;
}

/** Build a comparative fleet report as Markdown (Obsidian-friendly). */
export function buildFleetReport(
    agents: AgentInfo[],
    index: SessionIndex,
    insights: Insight[],
    days: number
): string {
    const now = Date.now();
    const cutoff = now - days * 24 * 3600 * 1000;
    const lines: string[] = [];
    const date = new Date().toISOString().slice(0, 10);

    lines.push(`# Agent Farm — Fleet Report (${date})`);
    lines.push('');
    lines.push(`Period: last **${days} days** · generated by Agent Farm · costs are API-equivalent values.`);
    lines.push('');

    // Fleet totals
    const all = index.all().filter(s => inRange(s, cutoff));
    const totalCost = all.reduce((a, s) => a + s.cost, 0);
    const totalTok = all.reduce((a, s) => a + totalTokens(s.usage), 0);
    const totalTools = all.reduce((a, s) => a + s.toolCalls, 0);
    const totalErrors = all.reduce((a, s) => a + s.errors, 0);
    lines.push('## Fleet totals');
    lines.push('');
    lines.push(`- Sessions: **${all.length}** · Cost: **${fmtUSD(totalCost)}** · Tokens: **${fmtTokens(totalTok)}**`);
    lines.push(`- Tool calls: **${totalTools}** · Errors: **${totalErrors}**${totalTools ? ` (${pct(totalErrors / totalTools)})` : ''}`);
    lines.push('');

    // Per-agent comparison
    lines.push('## Agent comparison');
    lines.push('');
    lines.push('| Agent | Sessions | Cost | Tokens | Tools | Err % | Cache eff. | Ctx load | Memory files |');
    lines.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
    for (const agent of agents) {
        const sessions = index.forAgent(agent.id).filter(s => inRange(s, cutoff));
        const cost = sessions.reduce((a, s) => a + s.cost, 0);
        const tok = sessions.reduce((a, s) => a + totalTokens(s.usage), 0);
        const tools = sessions.reduce((a, s) => a + s.toolCalls, 0);
        const errors = sessions.reduce((a, s) => a + s.errors, 0);
        const input = sessions.reduce((a, s) => a + s.usage.input + s.usage.cacheRead + s.usage.cacheWrite, 0);
        const cacheRead = sessions.reduce((a, s) => a + s.usage.cacheRead, 0);
        lines.push(`| ${agent.name} | ${sessions.length} | ${fmtUSD(cost)} | ${fmtTokens(tok)} | ${tools} | ` +
            `${tools ? pct(errors / tools) : '—'} | ${input ? pct(cacheRead / input) : '—'} | ` +
            `~${fmtTokens(agent.contextLoad.total)} | ${agent.memoryFiles.length} |`);
    }
    lines.push('');
    lines.push('> Cache eff. = cache-read share of all prompt tokens (higher is cheaper). ' +
        'Ctx load = CLAUDE.md + MEMORY.md + AGENTS.md, paid every session.');
    lines.push('');

    // Models
    const models = new Map<string, { cost: number; sessions: number }>();
    for (const s of all) {
        for (const m of s.models) {
            const entry = models.get(m) ?? { cost: 0, sessions: 0 };
            entry.cost += s.cost / s.models.length;
            entry.sessions++;
            models.set(m, entry);
        }
    }
    if (models.size) {
        lines.push('## Model usage');
        lines.push('');
        lines.push('| Model | Sessions | Cost |');
        lines.push('| --- | ---: | ---: |');
        for (const [m, v] of [...models].sort((a, b) => b[1].cost - a[1].cost)) {
            lines.push(`| ${m} | ${v.sessions} | ${fmtUSD(v.cost)} |`);
        }
        lines.push('');
    }

    // Top sessions
    const top = all.slice().sort((a, b) => b.cost - a.cost).slice(0, 8);
    if (top.length) {
        lines.push('## Most expensive sessions');
        lines.push('');
        lines.push('| Agent | Session | Cost | Tokens | Tools |');
        lines.push('| --- | --- | ---: | ---: | ---: |');
        for (const s of top) {
            lines.push(`| ${s.agentName ?? '?'} | ${s.title.replace(/\|/g, '\\|')} | ${fmtUSD(s.cost)} | ${fmtTokens(totalTokens(s.usage))} | ${s.toolCalls} |`);
        }
        lines.push('');
    }

    // Health findings
    lines.push('## Health findings');
    lines.push('');
    if (insights.length) {
        for (const i of insights) {
            const icon = i.severity === 'error' ? '⛔' : i.severity === 'warning' ? '⚠' : 'ℹ';
            lines.push(`- ${icon} **${i.agentName}** (${i.category}): ${i.message}`);
        }
    } else {
        lines.push('- No findings — healthy fleet. 🌿');
    }
    lines.push('');

    return lines.join('\n');
}
