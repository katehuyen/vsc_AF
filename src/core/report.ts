function pct(n: number): string {
    return (100 * n).toFixed(0) + '%';
}

function inRange(s: SessionInfo, cutoff: number): boolean {
    return s.lastTs >= cutoff;
}

/** Build a comparative fleet report as Markdown (Obsidian-friendly). */
export function buildFleetReport(
    agents: AgentInfo[],
    index: SessionIndex,
    insights: Insight[],
    days: number,
    /** D1: rolling quality average for the period, by agent id. */
    quality?: (agentId: string) => { avg?: number; count: number },
    /**
     * ‼️ X-112 — WHAT EACH SESSION'S FIGURES MEAN. The header used to say
     * "costs are API-equivalent values" and the ⚖ total "against the limit"
     * over every Claude session, including the ones Kimi or an API key served.
     * With it, each total says what it added; without it, the report states
     * no meaning it cannot back.
     */
    billing?: (s: SessionInfo) => BillingIdentity
): string {
    const now = Date.now();
    const cutoff = now - days * 24 * 3600 * 1000;
    const lines: string[] = [];
    const date = new Date().toISOString().slice(0, 10);
    const all = index.all().filter(s => inRange(s, cutoff));
    const dollars = billing ? sumDollars(all, s => s.cost, billing) : undefined;
    const mixedMark = (sum: { mixed: boolean } | undefined): string => sum?.mixed ? ' (mixed)' : '';

    lines.push(`# Agent Farm — Fleet Report (${date})`);
    lines.push('');
    lines.push(`Period: last **${days} days** · generated by Agent Farm · `
        + (!dollars ? 'what each dollar figure is (plan equivalent or a bill) is not recorded here.'
            : dollars.mixed ? 'costs are NOT one kind of dollar — a total marked (mixed) adds figures that mean different things; the breakdown is under Fleet totals.'
                : dollars.parts.length ? `costs are ${dollars.parts[0].label}.` : 'no session in the period has a cost.'));
    lines.push('');

    // Fleet totals
    const totalCost = all.reduce((a, s) => a + s.cost, 0);
    const totalTok = all.reduce((a, s) => a + totalTokens(s.usage), 0);
    const totalW = all.reduce((a, s) => a + s.wTokens, 0);
    const totalTools = all.reduce((a, s) => a + s.toolCalls, 0);
    const totalErrors = all.reduce((a, s) => a + s.errors, 0);
    // A run no record places is counted OFF the window: "against the limit" is
    // the claim that has to be earned.
    const weighed = billing ? splitWeighed(all, s => s.wTokens, billing) : undefined;
    lines.push('## Fleet totals');
    lines.push('');
    lines.push(`- Claude sessions: **${all.length}** · Cost: **${fmtUSD(totalCost)}**${mixedMark(dollars)} · ` +
        `Tokens: **${fmtTokens(totalTok)}** · ⚖ ` + (!weighed ? `**${fmtTokens(Math.round(totalW))}** weighted`
            : `**${fmtTokens(weighed.plan)}** against the plan limit`
            + (weighed.off ? ` · **${fmtTokens(weighed.off)}** off-plan (filled no five-hour window)` : '')));
    if (dollars?.mixed) {
        for (const l of describeDollars(dollars, fmtUSD)) { lines.push(`  - ${l}`); }
    }
    lines.push(`- Tool calls: **${totalTools}** · Errors: **${totalErrors}**${totalTools ? ` (${pct(totalErrors / totalTools)})` : ''}`);
    /**
     * ‼️ THE LINE ABOVE SAID "Sessions" AND MEANT "CLAUDE SESSIONS" (X-35).
     *
     * Everything measured in this report — cost, tokens, cache efficiency,
     * context load, quality — is defined against Claude's transcript format and
     * genuinely cannot be computed for the other engines, so the report stays
     * Claude's and that is the right call. What was NOT right is a heading that
     * says "Fleet totals" over a session count that quietly excluded three
     * engines: a reader comparing it against the Sessions page found a different
     * number and had nothing to explain the gap. The counts are stated, the
     * exclusion is stated, and neither is folded into the money.
     */
    const external = index.external().filter(s => inRange(s, cutoff));
    if (external.length) {
        lines.push(`- Other engines in the same period: **${external.length}** session${external.length === 1 ? '' : 's'}`
            + ` — ${engineSpread(external)}. Listed on the Sessions page; deliberately NOT in the figures`
            + ' above or anywhere below, because every measurement in this report is defined against'
            + ' Claude\'s transcript format and would read zero or read wrong on a foreign one.');
    }
    lines.push('');

    // Per-agent comparison
    lines.push('## Agent comparison');
    lines.push('');
    lines.push('| Agent | Sessions | Cost | Tokens | ⚖ Weighted | Tools | Err % | Quality | Cache eff. | Ctx load | Memory files |');
    lines.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
    for (const agent of agents) {
        const sessions = index.forAgent(agent.id).filter(s => inRange(s, cutoff));
        const cost = sessions.reduce((a, s) => a + s.cost, 0);
        const costMark = mixedMark(billing ? sumDollars(sessions, s => s.cost, billing) : undefined);
        const tok = sessions.reduce((a, s) => a + totalTokens(s.usage), 0);
        const wTok = sessions.reduce((a, s) => a + s.wTokens, 0);
        const tools = sessions.reduce((a, s) => a + s.toolCalls, 0);
        const errors = sessions.reduce((a, s) => a + s.errors, 0);
        const input = sessions.reduce((a, s) => a + s.usage.input + s.usage.cacheRead + s.usage.cacheWrite, 0);
        const cacheRead = sessions.reduce((a, s) => a + s.usage.cacheRead, 0);
        const q = quality?.(agent.id);
        const qCell = q?.avg !== undefined ? `${q.avg.toFixed(1)}/5 (${q.count})` : '—';
        lines.push(`| ${agent.name} | ${sessions.length} | ${fmtUSD(cost)}${costMark} |${fmtTokens(tok)} | ${fmtTokens(Math.round(wTok))} | ${tools} | ` +
            `${tools ? pct(errors / tools) : '—'} | ${qCell} | ${input ? pct(cacheRead / input) : '—'} | ` +
            `~${fmtTokens(agent.contextLoad.total)} | ${agent.memoryFiles.length} |`);
    }
    lines.push('');
    lines.push('> Cache eff. = cache-read share of all prompt tokens (higher is cheaper). ' +
        'Ctx load = CLAUDE.md + MEMORY.md + AGENTS.md, paid every session. ' +
        'Quality = cheap-model judge average (1-5) over sampled sessions in the period.');
    lines.push('');

    // Models
    const models = new Map<string, { cost: number; sessions: number }>();
    for (const s of all) {
        for (const m of s.models) {
            const entry = models.get(m) ?? { cost: 0, sessions: 0 };
            entry.cost += s.cost / s.models.length;
            entry.sessions++;
            models.set(m, entry);
        }
    }
    if (models.size) {
        lines.push('## Model usage');
        lines.push('');
        lines.push('| Model | Sessions | Cost |');
        lines.push('| --- | ---: | ---: |');
        for (const [m, v] of [...models].sort((a, b) => b[1].cost - a[1].cost)) {
            lines.push(`| ${m} | ${v.sessions} | ${fmtUSD(v.cost)} |`);
        }
        lines.push('');
    }

    // Top sessions
    const top = all.slice().sort((a, b) => b.cost - a.cost).slice(0, 8);
    if (top.length) {
        lines.push('## Most expensive sessions');
        lines.push('');
        lines.push('| Agent | Session | Cost | Tokens | ⚖ Weighted | Tools |');
        lines.push('| --- | --- | ---: | ---: | ---: | ---: |');
        for (const s of top) {
            lines.push(`| ${s.agentName ?? '?'} | ${s.title.replace(/\|/g, '\\|')} | ${fmtUSD(s.cost)} | ` +
                `${fmtTokens(totalTokens(s.usage))} | ${fmtTokens(Math.round(s.wTokens))} | ${s.toolCalls} |`);
        }
        lines.push('');
    }

    // Health findings
    lines.push('## Health findings');
    lines.push('');
    if (insights.length) {
        for (const i of insights) {
            const icon = i.severity === 'error' ? '⛔' : i.severity === 'warning' ? '⚠' : 'ℹ';
            lines.push(`- ${icon} **${i.agentName}** (${i.category}): ${i.message}`);
        }
    } else {
        lines.push('- No findings — healthy fleet. 🌿');
    }
    lines.push('');

    return lines.join('\n');
}

// ---------- E2: daily digest card (Telegram-friendly, no LLM) ----------

export interface DailyDigestData {
    date: string;
    todayCost: number;
    activeAgents: number;
    totalAgents: number;
    agents: { name: string; todayCost: number; budget?: number }[];
    warnings: string[];
    pendingDuties: number;
    runningTasks: number;
    queuedTasks: number;
    mediaCostToday: number;
    /** Tasks that finished today (done/failed) + a few failure titles. */
    taskOutcomesToday?: { done: number; failed: number; topFailures: string[]; costUSD?: number };
}

/**
 * Compact plain-text daily scorecard for phones (webhook → n8n → Telegram).
 * Pure data in, text out — no model call, no cost.
 */
export function buildDailyDigest(d: DailyDigestData): string {
    const lines: string[] = [];
    lines.push(`🤖 Agent Farm — ${d.date}`);
    lines.push(`Bugün: ${fmtUSD(d.todayCost)}` +
        (d.mediaCostToday > 0 ? ` (+${fmtUSD(d.mediaCostToday)} medya)` : '') +
        ` · ${d.activeAgents}/${d.totalAgents} ajan aktif`);
    const spenders = d.agents
        .filter(a => a.todayCost > 0)
        .sort((a, b) => b.todayCost - a.todayCost)
        .slice(0, 5)
        .map(a => `${a.name} ${fmtUSD(a.todayCost)}` +
            (a.budget && a.budget > 0 ? ` (%${Math.round(100 * a.todayCost / a.budget)})` : ''));
    if (spenders.length) { lines.push('Harcama: ' + spenders.join(' · ')); }
    if (d.runningTasks || d.queuedTasks) {
        lines.push(`Görevler: ${d.runningTasks} çalışıyor, ${d.queuedTasks} kuyrukta`);
    }
    const out = d.taskOutcomesToday;
    if (out && (out.done || out.failed)) {
        lines.push(`Bugün biten: ${out.done}✓ ${out.failed}✗` +
            (out.costUSD ? ` · ~$${out.costUSD.toFixed(2)}` : '') +
            (out.topFailures.length ? ` — hata: ${out.topFailures.slice(0, 2).join(', ')}` : ''));
    }
    if (d.pendingDuties) { lines.push(`👁 Nöbet: ${d.pendingDuties} bekleyen iş`); }
    if (d.warnings.length) {
        lines.push('⚠ ' + d.warnings.slice(0, 4).join(' | '));
    } else {
        lines.push('✅ Sağlık bulgusu yok');
    }
    return lines.join('\n').slice(0, 1500);
}

/** Digest of archived headless task outputs over a period. */
export function buildOutputsDigest(
    tasks: FarmTask[],
    sinceMs: number,
    maxCharsPerTask = 4000
): string {
    const now = Date.now();
    const cutoff = now - sinceMs;
    const finished = tasks
        .filter(t => t.outputFile && t.endedAt && t.endedAt >= cutoff &&
            (t.status === 'done' || t.status === 'failed'))
        .sort((a, b) => (b.endedAt ?? 0) - (a.endedAt ?? 0));

    const lines: string[] = [];
    lines.push(`# Agent Farm — Task Outputs Digest (${new Date().toISOString().slice(0, 10)})`);
    lines.push('');
    lines.push(`${finished.length} archived task output(s) in the selected period.`);
    lines.push('');
    for (const t of finished) {
        const mins = t.startedAt && t.endedAt ? Math.round((t.endedAt - t.startedAt) / 60000) : 0;
        lines.push(`## ${t.status === 'failed' ? '⛔ ' : ''}${t.title}`);
        lines.push('');
        lines.push(`- Agent: **${t.agentName}** · ${new Date(t.endedAt ?? 0).toLocaleString()} · ${mins} min · ${t.status}`);
        lines.push('');
        let content = '';
        try { content = fs.readFileSync(t.outputFile as string, 'utf8'); } catch { content = '(output file missing)'; }
        // Drop the archive header (everything up to the first ---) to keep the digest readable.
        const sep = content.indexOf('\n---\n');
        if (sep >= 0) { content = content.slice(sep + 5); }
        content = content.trim();
        if (content.length > maxCharsPerTask) {
            content = content.slice(0, maxCharsPerTask) + `\n\n… [truncated, ${content.length} chars total]`;
        }
        lines.push(content || '(empty output)');
        lines.push('');
        lines.push('---');
        lines.push('');
    }
    return lines.join('\n');
}

/**
 * B-9 — the cost anomaly report as a FUNCTION rather than a command body.
 *
 * It was built inline where it was shown, so the one document that answers
 * "why was today expensive" could only be produced by a person opening a
 * palette. The wording, the columns and the scope sentence are the command's,
 * unchanged; what moved is where they live.
 */
/** A session as this report reads it: its per-day costs AND its totals. */
export interface CostSession extends SessionCostRef {
    daily: Record<string, { cost: number }>;
}

export interface CostReportInput {
    now: number;
    minUsd: number;
    /** the X-35 sentence saying which engines these figures cover ('' = nothing to say) */
    scopeNote: string;
    fleet: CostSession[];
    perAgent: { name: string; sessions: CostSession[] }[];
}

export function buildCostReport(input: CostReportInput): string {
    const { now, minUsd } = input;
    const lines: string[] = [];
    lines.push('# Agent Farm — Cost Anomaly Report');
    lines.push('');
    lines.push(`Generated: ${new Date(now).toLocaleString()} · baseline: trailing 14 days (median + MAD)`);
    if (input.scopeNote) {
        lines.push('');
        lines.push(`> **Scope.** ${input.scopeNote}`);
    }
    lines.push('');
    lines.push('| Agent | Today | 14d median | Robust σ | Factor | Anomaly |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    const rowFor = (label: string, sessions: CostSession[]): void => {
        const hist = dailyCostHistory(sessions, 14, now);
        const today = todayCost(sessions, now);
        const med = hist.slice().sort((a, b) => a - b)[Math.floor(hist.length / 2)] ?? 0;
        const anomaly = detectCostAnomaly(hist, today, { minUsd });
        lines.push(`| ${label} | ${fmtUSD(today)} | ${fmtUSD(med)} | `
            + `${anomaly ? fmtUSD(anomaly.sigma) : '—'} | `
            + `${anomaly ? anomaly.factor.toFixed(1) + 'x' : '—'} | ${anomaly ? '⚠ YES' : 'no'} |`);
    };
    rowFor('**fleet**', input.fleet);
    for (const a of input.perAgent) { rowFor(a.name, a.sessions); }
    lines.push('');
    const hh = heavyHitters(input.fleet, 7 * 24 * 3600 * 1000, now);
    lines.push('## Heavy hitters (last 7 days)');
    lines.push('');
    lines.push(hh.sessionCount
        ? `**${hh.heavy.length} of ${hh.sessionCount} measured sessions (${hh.heavyCountPct}%) consume `
        + `${hh.tokenSharePct}% of the measured tokens** (${fmtTokens(hh.totalTokens)} total, ${fmtUSD(hh.totalCost)}).`
        : 'No measured sessions in the window.');
    lines.push('');
    for (const s of hh.heavy.slice(0, 10)) {
        lines.push(`- ${s.agentName ?? '?'} — "${s.title}" · ${fmtTokens(s.tokens)} tok · `
            + `${fmtUSD(s.cost)} · ${new Date(s.lastTs).toLocaleString()}`);
    }
    return lines.join('\n');
}

/** B-9 — trigger reliability, same move: the table lived in the command body. */
export function buildTriggerReport(stats: TriggerStat[], now = Date.now()): string {
    const lines: string[] = [];
    lines.push('# Agent Farm — Trigger Reliability');
    lines.push('');
    lines.push(`Generated: ${new Date(now).toLocaleString()} · window: last 7 days`);
    lines.push('');
    lines.push('| Trigger | Armed | Fired (total) | 7d ✓/✗ | Median start delay | Last fired | Flags |');
    lines.push('| --- | --- | --- | --- | --- | --- | --- |');
    for (const s of stats) {
        const delay = s.medianStartDelayMs !== undefined
            ? (s.medianStartDelayMs < 90_000
                ? Math.round(s.medianStartDelayMs / 1000) + 's'
                : Math.round(s.medianStartDelayMs / 60_000) + 'm')
            : '—';
        const flags = [
            s.neverFired ? 'never fired' : '',
            s.alwaysFails ? '⚠ always fails' : ''
        ].filter(Boolean).join(', ') || '—';
        lines.push(`| ${s.title} | ${s.enabled ? 'yes' : 'no'} | ${s.fireCountTotal} | `
            + `${s.ok7d}/${s.fail7d} | ${delay} | `
            + `${s.lastFiredAt ? new Date(s.lastFiredAt).toLocaleString() : 'never'} | ${flags} |`);
    }
    return lines.join('\n');
}
