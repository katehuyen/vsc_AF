/**
 * The `af-*` keys out of a document's frontmatter.
 *
 * Deliberately NOT a YAML parser: it reads `key: value` lines and simple `- `
 * lists inside the leading `---` block, and nothing else. Everything Agent Farm
 * stores in frontmatter is a scalar or a flat list by design, and a real parser
 * would be a dependency plus a promise to handle YAML we never write. Keys
 * outside the `af-` namespace are ignored — whatever else the user keeps up
 * there is theirs.
 */
export function readAfFrontmatter(text: string): Record<string, string | string[]> {
    const out: Record<string, string | string[]> = {};
    const m = /^\uFEFF?---\r?\n([\s\S]*?)\r?\n---(\r?\n|$)/.exec(String(text ?? ''));
    if (!m) { return out; }
    let listKey = '';
    for (const raw of m[1].split(/\r?\n/)) {
        const line = raw.replace(/\s+$/, '');
        if (!line.trim()) { continue; }
        const item = /^\s+-\s+(.*)$/.exec(line);
        if (item && listKey) {
            const value = item[1].trim().replace(/^['"]|['"]$/g, '');
            const cur = out[listKey];
            if (Array.isArray(cur)) { cur.push(value); } else { out[listKey] = [value]; }
            continue;
        }
        const kv = /^([A-Za-z][\w-]*)\s*:\s*(.*)$/.exec(line);
        if (!kv) { listKey = ''; continue; }
        const key = kv[1].toLowerCase();
        const value = kv[2].trim();
        if (!key.startsWith('af-')) { listKey = ''; continue; }
        if (!value) { listKey = key; out[key] = []; continue; }
        listKey = '';
        // an inline list: [a, b, c]
        const inline = /^\[(.*)\]$/.exec(value);
        if (inline) {
            out[key] = inline[1].split(',').map(s => s.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
        } else {
            out[key] = value.replace(/^['"]|['"]$/g, '');
        }
    }
    return out;
}

/** How much of a file we read looking for frontmatter. It is at the very top or
 *  it is not there; reading whole notes to find out would make a scan of a
 *  folder with 400 notes needlessly expensive. */
const FRONTMATTER_PROBE_BYTES = 2048;
/** Depth below the project folder that role discovery walks. */
const SCAN_DEPTH = 2;
/** Ceiling on files examined, so a folder somebody pointed at their whole disk
 *  degrades into "found nothing" rather than hanging the window. */
const SCAN_FILE_CAP = 600;

function probe(file: string): string {
    try {
        const fd = fs.openSync(file, 'r');
        try {
            const buf = Buffer.alloc(FRONTMATTER_PROBE_BYTES);
            const read = fs.readSync(fd, buf, 0, FRONTMATTER_PROBE_BYTES, 0);
            return buf.slice(0, read).toString('utf8');
        } finally { fs.closeSync(fd); }
    } catch { return ''; }
}

/** Every markdown file under `dir`, breadth-limited. */
function markdownFiles(dir: string): string[] {
    const out: string[] = [];
    const walk = (current: string, depth: number): void => {
        if (out.length >= SCAN_FILE_CAP) { return; }
        let entries: fs.Dirent[] = [];
        try { entries = fs.readdirSync(current, { withFileTypes: true }); } catch { return; }
        for (const e of entries) {
            if (out.length >= SCAN_FILE_CAP) { return; }
            const full = path.join(current, e.name);
            if (e.isDirectory()) {
                if (depth < SCAN_DEPTH) { walk(full, depth + 1); }
            } else if (e.name.toLowerCase().endsWith('.md')) {
                out.push(full);
            }
        }
    };
    walk(dir, 0);
    return out;
}

export type RoleMap = Partial<Record<ProjectDocRole, string>>;

/**
 * Which file holds which role. First one found wins and the rest are ignored:
 * two files claiming `charter` is a mistake in the folder, and picking one
 * quietly is better than refusing to show the project at all.
 */
export function scanRoles(dir: string): RoleMap {
    const map: RoleMap = {};
    if (!dirExists(dir)) { return map; }
    for (const file of markdownFiles(dir)) {
        const fm = readAfFrontmatter(probe(file));
        const role = fm['af-role'];
        if (typeof role !== 'string') { continue; }
        const key = role.trim().toLowerCase() as ProjectDocRole;
        if (PROJECT_DOC_ROLES.includes(key) && !map[key]) { map[key] = file; }
    }
    return map;
}

/**
 * Guarantee a role-carrying file can be identified.
 *
 * The skeleton is configurable, which means someone will eventually write a
 * charter template without `af-id` in it — and since Agent Farm finds documents
 * by frontmatter and nothing else, that project would come back from a folder
 * rescan as an unknown folder rather than itself. So a missing key is added.
 *
 * A key that is PRESENT is never touched, even when it disagrees with what we
 * expected: the user declaring a different role in their own file is a
 * statement, not a mistake to correct.
 */
export function ensureRoleFrontmatter(text: string, role: ProjectDocRole, vars: TemplateVars): string {
    const body = String(text ?? '');
    const fm = readAfFrontmatter(body);
    const missing: string[] = [];
    if (!fm['af-role']) { missing.push(`af-role: ${role}`); }
    if (role === 'charter' && !fm['af-id']) { missing.push(`af-id: ${vars.id}`); }
    if (!missing.length) { return body; }
    const opening = /^\uFEFF?---\r?\n/.exec(body);
    if (opening) {
        const at = opening[0].length;
        return body.slice(0, at) + missing.join('\n') + '\n' + body.slice(at);
    }
    return `---\n${missing.join('\n')}\n---\n\n${body}`;
}

