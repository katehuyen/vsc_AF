export function dirExists(dir: string): boolean {
    try { return !!dir && fs.statSync(dir).isDirectory(); } catch { return false; }
}

export interface RenameFolderResult {
    ok: boolean;
    /** the folder's path afterwards — the OLD one when the rename failed, so a
     *  caller that stores this can never end up pointing at nothing */
    path: string;
    error?: string;
}

/**
 * Rename a project's folder alongside its name.
 *
 * Failure is expected and handled rather than thrown: Obsidian may be holding a
 * file inside it open, and Windows will refuse. The caller keeps the old path
 * (which still exists and still works) and tells the user what to do — a name
 * and a folder that disagree is a cosmetic problem; a registry pointing at a
 * folder that is not there is a broken project.
 */
export function renameProjectFolder(from: string, newName: string): RenameFolderResult {
    if (!dirExists(from)) { return { ok: false, path: from, error: 'the current folder is not there' }; }
    const leaf = folderNameFor(newName);
    if (!leaf) { return { ok: false, path: from, error: 'that name has no usable characters for a folder' }; }
    const to = path.join(path.dirname(path.resolve(from)), leaf);
    if (path.resolve(from) === to) { return { ok: true, path: from }; }
    // a case-only rename is a move onto itself on Windows; let it through, but
    // anything else landing on an existing folder would merge two projects
    if (fs.existsSync(to) && to.toLowerCase() !== path.resolve(from).toLowerCase()) {
        return { ok: false, path: from, error: `a folder named "${leaf}" is already there` };
    }
    try {
        fs.renameSync(from, to);
        return { ok: true, path: to };
    } catch (e) {
        return {
            ok: false, path: from,
            error: `could not rename the folder (a file inside may be open): ${String(e)}`
        };
    }
}

