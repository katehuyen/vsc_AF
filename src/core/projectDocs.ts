const DELIVERABLES_TEMPLATE = `---
af-role: deliverables
---

# {project} — Deliverables

| What | Version | Date | Where |
|---|---|---|---|
`;

/**
 * The shipped default. English, because anything hard-coded is (the user writes
 * the CONTENT in whatever language they like). Folders carry a numeric prefix
 * purely so the file explorer orders them the same way everywhere; that is a
 * display convention, not a naming rule anybody has to keep.
 */
export const DEFAULT_SKELETON: SkeletonEntry[] = [
    { path: 'Charter.md', role: 'charter', template: CHARTER_TEMPLATE },
    { path: 'Plan.md', role: 'plan', template: PLAN_TEMPLATE },
    { path: 'People.md', role: 'people', template: PEOPLE_TEMPLATE },
    { path: 'Worklog.md', role: 'log', template: LOG_TEMPLATE },
    { path: '10_Notes/' },
    { path: '20_Decisions/', holds: 'decisions' },
    { path: '30_Deliverables/Deliverables.md', role: 'deliverables', template: DELIVERABLES_TEMPLATE },
    { path: '40_Resources/' },
    { path: '90_Archive/' },
    { path: '_AF/' }
];

/** Accept whatever the setting holds and return a usable skeleton. An entry
 *  that would escape the project folder is dropped, not sanitised: a path
 *  climbing out of the folder is never a typo worth guessing at. */
export function normalizeSkeleton(raw: unknown): SkeletonEntry[] {
    if (!Array.isArray(raw) || !raw.length) { return DEFAULT_SKELETON; }
    const out: SkeletonEntry[] = [];
    const seen = new Set<string>();
    for (const item of raw) {
        const o = typeof item === 'string' ? { path: item } : item as Record<string, unknown>;
        if (!o || typeof o !== 'object') { continue; }
        const rel = typeof o.path === 'string' ? o.path.trim().replace(/\\/g, '/') : '';
        if (!rel || rel.startsWith('/') || /(^|\/)\.\.(\/|$)/.test(rel) || /^[A-Za-z]:/.test(rel)) { continue; }
        const key = rel.toLowerCase();
        if (seen.has(key)) { continue; }
        seen.add(key);
        const entry: SkeletonEntry = { path: rel };
        if (PROJECT_DOC_ROLES.includes(o.role as ProjectDocRole)) { entry.role = o.role as ProjectDocRole; }
        if (typeof o.template === 'string' && o.template) { entry.template = o.template; }
        if (o.holds === 'decisions') { entry.holds = 'decisions'; }
        out.push(entry);
    }
    return out.length ? out : DEFAULT_SKELETON;
}

export interface TemplateVars {
    project: string;
    id: string;
    status: string;
    /** YYYY-MM-DD */
    date: string;
    /** YYMMDD — for vaults whose file names carry a date */
    yymmdd: string;
}

/**
 * ‼️ EVERY DATE THIS MODULE PRINTS IS LOCAL, AND THAT IS NOT A PREFERENCE.
 *
 * A project's Started/Due is stored as LOCAL midnight — the page's date picker
 * builds it as `new Date(value + 'T00:00:00')`. Formatting that through
 * `toISOString()` prints the day BEFORE anywhere east of UTC: measured at +07, a
 * due date entered as 15 August reached the agent as 14 August, and a form that
 * read the value back the same way lost another day on every save.
 *
 * One pair of helpers, used by everything here, so the two cannot diverge again.
 */
function pad2(n: number): string { return String(n).padStart(2, '0'); }

/** YYYY-MM-DD, local. */
export function localDay(ms: number): string {
    const d = new Date(ms);
    return `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`;
}

/** YYYY-MM-DD HH:MM, local — the same shape the context header uses, so the two
 *  stamps inside one brief cannot disagree by a timezone. Exported because the
 *  bridge prints project timestamps too, and a UTC one there would tell an agent
 *  a different hour (and east of UTC, a different day) than the page shows. */
export function localStamp(ms: number): string {
    const d = new Date(ms);
    return `${localDay(ms)} ${pad2(d.getHours())}:${pad2(d.getMinutes())}`;
}

export function templateVars(project: Project, now = new Date()): TemplateVars {
    const date = localDay(now.getTime());
    return {
        project: project.name,
        id: project.id,
        status: project.status,
        date,
        yymmdd: date.slice(2).replace(/-/g, '')
    };
}

/** Expand `{project}` and friends. Unknown placeholders are left alone — a
 *  template full of `{}` from some other system should look wrong, not silently
 *  lose the braces. */
export function renderTemplate(text: string, vars: TemplateVars): string {
    return String(text ?? '').replace(/\{(project|id|status|date|yymmdd)\}/g,
        (_m, key: keyof TemplateVars) => String(vars[key] ?? ''));
}

/** Resolve a skeleton path inside the folder, or undefined if it escapes.
 *  A `{project}` inside the path is sanitised the way a folder name is, so a
 *  project called `a/b` cannot silently create a nested directory. */
function resolveInside(dir: string, rel: string, vars: TemplateVars): string | undefined {
    const safeVars: TemplateVars = { ...vars, project: folderNameFor(vars.project) };
    const rendered = renderTemplate(rel, safeVars);
    if (!rendered.trim()) { return undefined; }
    const base = path.resolve(dir);
    const target = path.resolve(base, rendered);
    if (target !== base && !target.startsWith(base + path.sep)) { return undefined; }
    return target;
}

export interface SkeletonResult {
    created: string[];
    /** already there — never touched */
    skipped: string[];
    failed: { path: string; error: string }[];
}

/**
 * Build (or complete) a project's folder.
 *
 * Safe to run on a folder that already has content: anything present is left
 * exactly as it is. That is what makes "Recreate" usable on a project whose
 * folder was moved and half-restored — it fills the gaps and touches nothing
 * else.
 */
export function createSkeleton(
    dir: string, project: Project, skeleton: SkeletonEntry[] = DEFAULT_SKELETON, now = new Date()
): SkeletonResult {
    const vars = templateVars(project, now);
    const result: SkeletonResult = { created: [], skipped: [], failed: [] };
    try { fs.mkdirSync(dir, { recursive: true }); } catch (e) {
        result.failed.push({ path: dir, error: String(e) });
        return result;
    }
    for (const entry of skeleton) {
        const isFolder = entry.path.endsWith('/');
        const target = resolveInside(dir, entry.path.replace(/\/$/, ''), vars);
        if (!target) {
            result.failed.push({ path: entry.path, error: 'path escapes the project folder' });
            continue;
        }
        try {
            if (isFolder) {
                if (fs.existsSync(target)) { result.skipped.push(target); continue; }
                fs.mkdirSync(target, { recursive: true });
                result.created.push(target);
                continue;
            }
            if (fs.existsSync(target)) { result.skipped.push(target); continue; }
            fs.mkdirSync(path.dirname(target), { recursive: true });
            let body = renderTemplate(entry.template ?? '', vars);
            if (entry.role) { body = ensureRoleFrontmatter(body, entry.role, vars); }
            fs.writeFileSync(target, body, 'utf8');
            result.created.push(target);
        } catch (e) {
            result.failed.push({ path: entry.path, error: String(e) });
        }
    }
    return result;
}

