export interface ScannedProject {
    /** af-id from the charter, when it has one */
    id?: string;
    /** the folder's own name — the project's name as the user sees it */
    name: string;
    folder: string;
    status?: string;
    kind?: string;
    /** true when no charter with an af-id was found */
    unregistered: boolean;
}

/**
 * Walk a projects root and report what is actually there.
 *
 * This is what makes the registry rebuildable and what lets the user rename a
 * project BY RENAMING ITS FOLDER in Obsidian: the identity lives in the
 * charter's `af-id`, so the folder can be called anything and still be
 * recognised as the same project.
 *
 * A duplicate `af-id` (someone copied a folder to start a second project) is
 * reported as unregistered rather than silently claiming to be the original —
 * two projects with one id would corrupt every link that hangs off it.
 */
export function scanProjectsRoot(root: string): ScannedProject[] {
    if (!dirExists(root)) { return []; }
    let entries: fs.Dirent[] = [];
    try { entries = fs.readdirSync(root, { withFileTypes: true }); } catch { return []; }

    const out: ScannedProject[] = [];
    const seenIds = new Set<string>();
    for (const e of entries) {
        if (!e.isDirectory() || e.name.startsWith('.')) { continue; }
        const folder = path.join(root, e.name);
        const roles = scanRoles(folder);
        const found: ScannedProject = { name: e.name, folder, unregistered: true };
        if (roles.charter) {
            const fm = readAfFrontmatter(probe(roles.charter));
            const id = typeof fm['af-id'] === 'string' ? String(fm['af-id']).trim() : '';
            const status = typeof fm['af-status'] === 'string' ? String(fm['af-status']).trim() : '';
            const kind = typeof fm['af-kind'] === 'string' ? String(fm['af-kind']).trim() : '';
            if (id && !seenIds.has(id)) {
                seenIds.add(id);
                found.id = id;
                found.unregistered = false;
            }
            if (status) { found.status = status; }
            if (kind) { found.kind = kind; }
        }
        out.push(found);
    }
    return out;
}
