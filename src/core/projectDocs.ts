export interface WriteResult {
    ok: boolean;
    error?: string;
    /** the file's mtime after a successful write — hand it back on the next
     *  guarded write to prove nothing changed in between */
    mtimeMs?: number;
}

export function docMtime(file: string): number {
    try { return fs.statSync(file).mtimeMs; } catch { return 0; }
}

/**
 * Write a document, atomically, optionally refusing if it changed since the
 * caller read it.
 *
 * The guard is the whole point. These files are open in Obsidian while we work;
 * a blind write loses whatever the user typed a minute ago, and they would have
 * no idea it ever existed. Refusing costs one message; overwriting costs their
 * afternoon.
 */
export function safeWriteDoc(file: string, content: string, expectedMtimeMs?: number): WriteResult {
    if (expectedMtimeMs !== undefined) {
        const current = docMtime(file);
        if (current !== expectedMtimeMs) {
            return {
                ok: false,
                error: 'the file changed since it was read — it was not overwritten'
            };
        }
    }
    const tmp = `${file}.af.tmp`;
    try {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(tmp, content, 'utf8');
        fs.renameSync(tmp, file);
        return { ok: true, mtimeMs: docMtime(file) };
    } catch (e) {
        try { if (fs.existsSync(tmp)) { fs.unlinkSync(tmp); } } catch { /* best effort */ }
        return { ok: false, error: String(e) };
    }
}

/**
 * Put a new entry in the worklog.
 *
 * It goes directly below the anchor line, so the newest is on top — and because
 * the position is a marker rather than a rule, a user who wants oldest-first
 * simply moves the anchor to the bottom of the file. With no anchor (a log the
 * user rewrote entirely) the entry is appended, which is always safe.
 */
export function insertLogEntry(file: string, entry: string): WriteResult {
    const text = String(entry ?? '').trim();
    if (!text) { return { ok: false, error: 'nothing to write' }; }
    let existing = '';
    try { existing = fs.readFileSync(file, 'utf8'); } catch { existing = ''; }

    if (!existing.trim()) {
        return safeWriteDoc(file, `${LOG_ANCHOR}\n\n${text}\n`);
    }
    const at = existing.indexOf(LOG_ANCHOR);
    if (at < 0) {
        const sep = existing.endsWith('\n') ? '' : '\n';
        return safeWriteDoc(file, `${existing}${sep}\n${text}\n`);
    }
    const after = at + LOG_ANCHOR.length;
    const head = existing.slice(0, after);
    // drop the blank line that sat between the anchor and whatever follows, so
    // repeated inserts do not grow a gap
    const tail = existing.slice(after).replace(/^\s*\n/, '');
    return safeWriteDoc(file, `${head}\n\n${text}\n\n${tail}`);
}

