import * as fs from 'fs';
import * as path from 'path';
import { folderNameFor, Project } from './projects';

/**
 * The project's folder — the copy that outlives everything else.
 *
 * The registry (projectStore) is an index this machine keeps; THIS is where the
 * project actually is. It travels in git with the vault, opens in Obsidian with
 * no extension running, and can rebuild the registry if that file is ever lost.
 *
 * One rule shapes the whole module: **Agent Farm never depends on a file's
 * name.** Documents are found by an `af-role` line in their frontmatter, so the
 * user can rename anything, move it into a subfolder, or write it in any
 * language, and nothing breaks. That is also why the skeleton is configurable
 * (`agentFarm.projectSkeleton`): the shipped default is one opinion, not a
 * requirement, and a vault with its own naming convention can state its own.
 *
 * Writing is deliberately timid. These are the user's files, opened in another
 * application that may be holding them at this moment:
 *   - nothing that exists is ever overwritten by skeleton creation;
 *   - a write can be guarded by the mtime the caller last read, so an edit made
 *     in Obsidian since then aborts the write instead of erasing it;
 *   - every write is atomic (temp file, then rename), so a crash mid-write
 *     cannot leave a truncated document;
 *   - log entries are INSERTED at an anchor the user can move, never appended
 *     by rewriting the file.
 *
 * Pure node (fs only) — no vscode — so all of it is testable.
 */

// ---------------------------------------------------------------------------
// roles
// ---------------------------------------------------------------------------

/** What a document IS, independent of what it is called. */
export type ProjectDocRole = 'charter' | 'plan' | 'people' | 'log' | 'deliverables' | 'brief';
export const PROJECT_DOC_ROLES: ProjectDocRole[] =
    ['charter', 'plan', 'people', 'log', 'deliverables', 'brief'];

/** Where new log entries go. The user can move this line to change that — the
 *  mechanism is a marker, not a hard-coded position. */
export const LOG_ANCHOR = '<!-- af:log-top -->';

/** Stamped on files Agent Farm generates and will regenerate. */
export const MANAGED_BANNER = '<!-- af:managed — generated by Agent Farm; do not edit by hand -->';

