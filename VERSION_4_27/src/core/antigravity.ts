import * as fs from 'fs';
import * as path from 'path';
import { Duty } from './duties';
import { hashString, safeReadFile } from './util';

/**
 * Antigravity compatibility layer. A Claude-optimized agent can also run
 * under Google Antigravity: the instruction file standard there is AGENTS.md
 * (workspace root, cross-tool), with workspace extras under `.agents/`
 * (workflows/, skills/) and MCP config in the global
 * ~/.gemini/config/mcp_config.json (same mcpServers shape as .mcp.json).
 * Memory files are plain markdown read on demand — shared as-is, no
 * conversion needed.
 *
 * This is a *directional sync*, not a one-shot export: a sidecar records
 * content hashes at sync time, so later runs can tell which side moved
 * (CLAUDE.md, AGENTS.md, both) and reconcile in the right direction.
 */

export const AGENTS_MD_NAME = 'AGENTS.md';
export const SYNC_MARKER =
    '<!-- agent-farm:antigravity-sync — generated from CLAUDE.md. ' +
    'Edit freely; "Sync Agent with Antigravity" detects changes on either side and reconciles. -->';
const SIDECAR_REL = path.join('.agents', 'af-antigravity-sync.json');
const DUTY_MARKER = '<!-- agent-farm:duty-workflow -->';

export interface SyncSidecar {
    /** hash of CLAUDE.md content at last sync */
    srcHash: number;
    /** hash of the AGENTS.md body (marker stripped) we generated at last sync */
    genHash: number;
    ts: number;
    /** duty workflow files we generated: relative file → content hash */
    workflows: Record<string, number>;
}

export type AntigravityState =
    | 'none'              // never synced, no AGENTS.md
    | 'foreign'           // AGENTS.md exists but was not generated by us
    | 'in-sync'
    | 'claude-ahead'      // CLAUDE.md changed since last sync
    | 'antigravity-ahead' // AGENTS.md changed since last sync
    | 'conflict';         // both changed

/** Self-references must follow the file they live in. */
export function transformClaudeToAgents(body: string): string {
    return body.replace(/\bCLAUDE\.md\b/g, AGENTS_MD_NAME);
}

export function transformAgentsToClaude(body: string): string {
    return body.replace(/\bAGENTS\.md\b/g, 'CLAUDE.md');
}

export function buildAgentsMd(claudeBody: string): string {
    return SYNC_MARKER + '\n\n' + transformClaudeToAgents(claudeBody);
}

/** AGENTS.md content → body without our marker header. */
export function stripMarker(content: string): string {
    if (content.startsWith(SYNC_MARKER)) {
        return content.slice(SYNC_MARKER.length).replace(/^\s+/, '');
    }
    return content;
}

export function dutySlug(title: string): string {
    return title.toLowerCase()
        .replace(/ç/g, 'c').replace(/ğ/g, 'g').replace(/ı/g, 'i')
        .replace(/ö/g, 'o').replace(/ş/g, 's').replace(/ü/g, 'u')
        .replace(/[^a-z0-9\s-]/g, '')
        .trim()
        .replace(/\s+/g, '-') || 'duty';
}

/** A standing duty becomes an Antigravity workflow (invocable as /slug). */
export function dutyWorkflow(duty: Duty): { file: string; content: string } {
    const lines = [
        '---',
        `description: ${duty.title} (Agent Farm standing duty, cadence: ${duty.cadence})`,
        '---',
        '',
        DUTY_MARKER,
        '',
        `# ${duty.title}`,
        ''
    ];
    if (duty.watch) { lines.push(`1. Check the watch target: ${duty.watch}`); }
    lines.push(`${duty.watch ? '2' : '1'}. ${duty.action || 'Do what DUTIES.md describes for this duty.'}`);
    lines.push('');
    lines.push(`Cadence: ${duty.cadence}. The canonical definition lives in DUTIES.md — keep that file the source of truth.`);
    return {
        file: path.join('.agents', 'workflows', dutySlug(duty.title) + '.md'),
        content: lines.join('\n') + '\n'
    };
}

export function readSidecar(agentDir: string): SyncSidecar | undefined {
    try {
        const json = JSON.parse(fs.readFileSync(path.join(agentDir, SIDECAR_REL), 'utf8')) as SyncSidecar;
        if (typeof json.srcHash === 'number' && typeof json.genHash === 'number') {
            return { ...json, workflows: json.workflows ?? {} };
        }
    } catch { /* no sidecar */ }
    return undefined;
}

function writeSidecar(agentDir: string, sidecar: SyncSidecar): void {
    const file = path.join(agentDir, SIDECAR_REL);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(sidecar, null, 2), 'utf8');
}

export function antigravityStatus(agentDir: string): { state: AntigravityState; claudeChanged: boolean; agentsChanged: boolean } {
    const agentsContent = safeReadFile(path.join(agentDir, AGENTS_MD_NAME));
    const sidecar = readSidecar(agentDir);
    if (agentsContent === undefined) {
        return { state: 'none', claudeChanged: false, agentsChanged: false };
    }
    if (!sidecar) {
        return {
            state: agentsContent.startsWith(SYNC_MARKER) ? 'claude-ahead' : 'foreign',
            claudeChanged: true,
            agentsChanged: false
        };
    }
    const claude = safeReadFile(path.join(agentDir, 'CLAUDE.md')) ?? '';
    const claudeChanged = hashString(claude) !== sidecar.srcHash;
    const agentsChanged = hashString(stripMarker(agentsContent)) !== sidecar.genHash;
    const state: AntigravityState =
        claudeChanged && agentsChanged ? 'conflict'
            : claudeChanged ? 'claude-ahead'
                : agentsChanged ? 'antigravity-ahead'
                    : 'in-sync';
    return { state, claudeChanged, agentsChanged };
}

function backupFile(file: string): string | undefined {
    try {
        const backup = `${file}.${Date.now()}.afbak`;
        fs.copyFileSync(file, backup);
        return backup;
    } catch { return undefined; }
}

export interface SyncResult {
    written: string[];
    skipped: string[];
    backups: string[];
    notes: string[];
}

/**
 * Forward sync: CLAUDE.md → AGENTS.md (+ duty workflows + MCP suggestion).
 * Duty workflow files are only overwritten if untouched since we wrote them.
 */
export function syncToAntigravity(
    agentDir: string,
    duties: Duty[],
    opts: { force?: boolean } = {}
): SyncResult {
    const result: SyncResult = { written: [], skipped: [], backups: [], notes: [] };
    const claude = safeReadFile(path.join(agentDir, 'CLAUDE.md'));
    if (claude === undefined) {
        result.notes.push('CLAUDE.md not found — nothing to sync.');
        return result;
    }

    const agentsPath = path.join(agentDir, AGENTS_MD_NAME);
    const existing = safeReadFile(agentsPath);
    if (existing !== undefined && !existing.startsWith(SYNC_MARKER) && !opts.force) {
        result.skipped.push(AGENTS_MD_NAME);
        result.notes.push('AGENTS.md exists but was not generated by Agent Farm — re-run with overwrite confirmation.');
        return result;
    }
    if (existing !== undefined && !existing.startsWith(SYNC_MARKER)) {
        const b = backupFile(agentsPath);
        if (b) { result.backups.push(b); }
    }

    const agentsContent = buildAgentsMd(claude);
    fs.writeFileSync(agentsPath, agentsContent, 'utf8');
    result.written.push(AGENTS_MD_NAME);

    const sidecar: SyncSidecar = {
        srcHash: hashString(claude),
        genHash: hashString(stripMarker(agentsContent)),
        ts: Date.now(),
        workflows: {}
    };
    const previous = readSidecar(agentDir);

    for (const duty of duties.filter(d => !d.paused)) {
        const wf = dutyWorkflow(duty);
        const full = path.join(agentDir, wf.file);
        const current = safeReadFile(full);
        const prevHash = previous?.workflows[wf.file.replace(/\\/g, '/')];
        if (current !== undefined && !current.includes(DUTY_MARKER)) {
            result.skipped.push(wf.file);
            result.notes.push(`${wf.file}: a workflow with this name already exists (not ours) — left untouched.`);
            continue;
        }
        if (current !== undefined && prevHash !== undefined && hashString(current) !== prevHash) {
            result.skipped.push(wf.file);
            result.notes.push(`${wf.file}: edited by hand since the last sync — left untouched.`);
            sidecar.workflows[wf.file.replace(/\\/g, '/')] = hashString(current);
            continue;
        }
        fs.mkdirSync(path.dirname(full), { recursive: true });
        fs.writeFileSync(full, wf.content, 'utf8');
        result.written.push(wf.file);
        sidecar.workflows[wf.file.replace(/\\/g, '/')] = hashString(wf.content);
    }

    // MCP: Antigravity reads a global mcp_config.json (same mcpServers shape).
    // We never write into ~/.gemini ourselves — we prepare a merge-ready snippet.
    const mcpRaw = safeReadFile(path.join(agentDir, '.mcp.json'));
    if (mcpRaw) {
        try {
            const parsed = JSON.parse(mcpRaw) as { mcpServers?: Record<string, unknown> };
            if (parsed.mcpServers && Object.keys(parsed.mcpServers).length) {
                const suggested = path.join(agentDir, '.agents', 'mcp_config.suggested.json');
                fs.mkdirSync(path.dirname(suggested), { recursive: true });
                fs.writeFileSync(suggested,
                    JSON.stringify({ mcpServers: parsed.mcpServers }, null, 2), 'utf8');
                result.written.push(path.join('.agents', 'mcp_config.suggested.json'));
                result.notes.push('MCP: merge .agents/mcp_config.suggested.json into ~/.gemini/config/mcp_config.json (Antigravity reads MCP globally).');
            }
        } catch { result.notes.push('.mcp.json is not valid JSON — MCP suggestion skipped.'); }
    }

    result.notes.push('memory/ needs no conversion — plain markdown, referenced from AGENTS.md just like CLAUDE.md.');
    writeSidecar(agentDir, sidecar);
    return result;
}

/** Reverse sync: hand-edited AGENTS.md → CLAUDE.md (with backup). */
export function syncToClaude(agentDir: string): SyncResult {
    const result: SyncResult = { written: [], skipped: [], backups: [], notes: [] };
    const agentsContent = safeReadFile(path.join(agentDir, AGENTS_MD_NAME));
    if (agentsContent === undefined) {
        result.notes.push('AGENTS.md not found.');
        return result;
    }
    const claudePath = path.join(agentDir, 'CLAUDE.md');
    if (fs.existsSync(claudePath)) {
        const b = backupFile(claudePath);
        if (b) { result.backups.push(b); }
    }
    const newClaude = transformAgentsToClaude(stripMarker(agentsContent));
    fs.writeFileSync(claudePath, newClaude, 'utf8');
    result.written.push('CLAUDE.md');

    // Re-stamp AGENTS.md with the marker so both sides now agree.
    const restamped = buildAgentsMd(newClaude);
    fs.writeFileSync(path.join(agentDir, AGENTS_MD_NAME), restamped, 'utf8');
    result.written.push(AGENTS_MD_NAME);

    const previous = readSidecar(agentDir);
    writeSidecar(agentDir, {
        srcHash: hashString(newClaude),
        genHash: hashString(stripMarker(restamped)),
        ts: Date.now(),
        workflows: previous?.workflows ?? {}
    });
    return result;
}
