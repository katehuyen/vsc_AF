#!/usr/bin/env node
/**
 * U-238 — media/theme-phone.css: VS Code's LIGHT colours for a page the phone opens. A webview gets
 * its theme's --vscode-* colours from VS Code; a page served to the phone gets none, so every colour
 * falls back to the dark value written beside it. On a light device the phone puts vscode-light on
 * the body (media/afRemote.js) and this sheet gives the variables VS Code's Light Modern values —
 * read off the installed VS Code by tools/theme_vars.js into test/theme_vars.json. Dark defines
 * nothing: the phone's dark is the look it always had.
 *
 *   node tools/theme_phone.js        rewrite media/theme-phone.css from test/theme_vars.json
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'media', 'theme-phone.css');

/** The sheet for a theme_vars.json table — one variable per line, sorted. The ground is the table's own, written
 *  plainly (U-220): nobody customises a colour on the phone, and the theme layer derives --af-ground with a
 *  relative colour, a syntax a phone's browser may be older than. This sheet is linked after the layer. */
function phoneSheet(table) {
    const light = table.themes.light;
    const lines = Object.keys(light).sort().map(k => `    --vscode-${k}: ${light[k]};`);
    return '/* Generated by tools/theme_phone.js from test/theme_vars.json (VS Code ' + table.vscode + ', Light Modern) — do not edit. */\n'
        + 'body.vscode-light {\n    color-scheme: light;\n    --af-ground: ' + light['editor-background'] + ';\n' + lines.join('\n') + '\n}\n';
}

if (require.main === module) {
    const table = JSON.parse(fs.readFileSync(path.join(ROOT, 'test', 'theme_vars.json'), 'utf8'));
    fs.writeFileSync(OUT, phoneSheet(table), 'utf8');
    console.log(OUT);
}
module.exports = { phoneSheet };
